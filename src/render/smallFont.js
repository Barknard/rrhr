export const SMALL_W = 5, SMALL_H = 7, SMALL_ADVANCE = 6;
export const hasSmallGlyph = ch => Object.hasOwn(GLYPHS, ch);
export const smallWidth = str => Math.max(0, String(str).length * SMALL_ADVANCE - 1);

export function drawSmall(ctx, str, x, y, color, shadow = '#000') {
  str = String(str).toUpperCase();
  x = Math.round(x); y = Math.round(y);
  for (const [d, col] of shadow ? [[1, shadow], [0, color]] : [[0, color]]) {
    ctx.fillStyle = col;
    for (let i = 0; i < str.length; i++) {
      const g = GLYPHS[str[i]] || GLYPHS[' '];
      for (let b = 0; b < 35; b++) if (g[b] === '1') ctx.fillRect(x + i * SMALL_ADVANCE + (b % 5) + d, y + ((b / 5) | 0) + d, 1, 1);
    }
  }
}
