export const textWidth = (str, scale = 1) => Math.max(0, String(str).length * 4 - 1) * scale;

export function drawText(ctx, str, x, y, color, shadow = '#000', scale = 1) {
  str = String(str).toUpperCase();
  x = Math.round(x); y = Math.round(y);
  for (const [dx, col] of shadow ? [[scale, shadow], [0, color]] : [[0, color]]) {
    ctx.fillStyle = col;
    for (let i = 0; i < str.length; i++) {
      const g = GLYPHS[str[i]] || GLYPHS[' '];
      for (let b = 0; b < 15; b++) if (g[b] === '1') ctx.fillRect(x + (i * 4 + (b % 3)) * scale + dx, y + ((b / 3) | 0) * scale + dx, scale, scale);
    }
  }
}

export const drawCentered = (ctx, str, cx, y, color, shadow, scale = 1) => drawText(ctx, str, cx - textWidth(str, scale) / 2, y, color, shadow, scale);
